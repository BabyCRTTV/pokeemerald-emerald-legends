#!/usr/bin/env python3
"""Separate Mom's shared hair material and bake the owner-approved ROM palettes."""
import re
from pathlib import Path
from PIL import Image
from build_appearance import frames, pack
from preview_family_skin import SOURCES, skin_mask, packed

ROOT = Path(__file__).resolve().parents[2]

def build():
    text = (ROOT/'src/data/legends/appearance_palettes.h').read_text()
    body = re.search(r'sSkinPalettes\[5\]\[3\] = \{(.*?)\n\};', text, re.S)[1]
    ramps = [[int(v,16) for v in row.split(',')] for row in re.findall(r'\{([^}]+)\}',body)]
    output = ['// Generated by tools/legends/build_family_skin.py; do not edit.']
    for name,symbol in [('mom','Mom'),('norman','Norman'),('battle','NormanBattle')]:
        image = Image.open(ROOT/SOURCES[name]); pal = image.getpalette()
        native = [packed(pal[i*3:i*3+3]) for i in range(16)]
        palettes = []
        for ramp in ramps:
            colors = list(native); colors[1:4] = ramp
            if name == 'mom':
                colors[12] = native[3] # private hair highlights; unused in native Mom
            if name == 'battle':
                channels = lambda c:(c&31,c>>5&31,c>>10&31)
                edge,shade,deep = map(channels,(native[4],native[3],ramp[2]))
                c = [round(v*e/s) for v,e,s in zip(deep,edge,shade)]
                colors[4] = c[0]|c[1]<<5|c[2]<<10
            palettes.append(colors)
        output.append(f'const u16 gLegends{symbol}Palettes[5][16] = {{')
        output.extend('    {'+', '.join(f'0x{v:04X}' for v in row)+'},' for row in palettes)
        output.append('};\n')
    (ROOT/'src/data/legends/family_palettes.h').write_text('\n'.join(output).rstrip()+'\n')
    poses = frames(ROOT/SOURCES['mom'],16,32)
    for pixels in poses:
        mask = skin_mask('mom',pixels)
        assert not any(12 in row for row in pixels)
        for y,row in enumerate(pixels):
            for x,v in enumerate(row):
                if v in (1,2,3) and (x,y) not in mask:
                    assert v == 3
                    row[x] = 12
    out = ROOT/'graphics/legends/family/mom.4bpp'
    out.parent.mkdir(parents=True,exist_ok=True)
    out.write_bytes(b''.join(pack(p) for p in poses))

if __name__ == '__main__': build()
