"""Generate engine tables and the explicitly requested LegendsDex grotto supplement."""
from pathlib import Path
import json,hashlib
ROOT=Path(__file__).resolve().parents[2]
def main():
    path=ROOT/'src/data/legends/grotto_encounters.json';raw=path.read_bytes();source=json.loads(raw)
    seasons=['spring','summer','autumn','winter'];lines=['// Generated by tools/legends/build_grotto_encounters.py.','static const struct GrottoEncounter sGrottoEncounters[3][4][5] = {']
    data_path=ROOT/'docs/wiki/dex-data.json';wiki=json.loads(data_path.read_text());known={p['id'] for p in wiki['species']};maps=[]
    for room in source['rooms']:
        lines.append('    {');variants=[]
        for season in seasons:
            entries=room['seasons'][season];assert len(entries)==5 and sum(e['weight'] for e in entries)==100
            assert all(e['species'] in known for e in entries)
            lines.append('        {'+', '.join('{SPECIES_'+e['species']+', '+str(e['weight'])+'}' for e in entries)+'},')
            variants.append({'season':season,'entries':[dict(id=e['species'],min=room['levels'][0],max=room['levels'][1],rate=e['weight'],seasons=[season],time='all-day') for e in entries]})
        lines.append('    },')
        maps.append(dict(id=room['map'],name=room['name'],region='Grotto',parentRegion='Hoenn',description=room['entrance']+' · One visible visitor. After capture or defeat, take 4,500 steps to renew it. Fleeing or losing preserves the visitor.',methods=[dict(id='grotto',label='Grotto visitor',encounterRate=100,entries=variants[2]['entries'],seasonalVariants=variants)]))
    lines+=['};','static const u8 sGrottoLevels[3][2] = {'+', '.join('{'+str(r['levels'][0])+', '+str(r['levels'][1])+'}' for r in source['rooms'])+'};','']
    (ROOT/'src/data/legends/grotto_encounters.h').write_text('\n'.join(lines))
    wiki['maps']=[m for m in wiki['maps'] if m.get('region')!='Grotto']+maps
    wiki['grottoSource']={'path':'src/data/legends/grotto_encounters.json','sha256':hashlib.sha256(raw).hexdigest(),'refreshSteps':source['refreshSteps'],'status':'review'}
    data_path.write_text(json.dumps(wiki,ensure_ascii=False,indent=2)+'\n')
    print('Generated three grotto tables, 60 seasonal slots and exact wiki shares.')
if __name__=='__main__':main()
