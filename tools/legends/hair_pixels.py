"""Hair clusters inspired by the supplied Brendan/May reference sheets.

These are indexed native-grid assets: # is the native outline, + the brown
midtone and H the warm highlight. Directional overworld art is authored at its
own resolution. Faces/eyes are composited from the unchanged native sprite.
"""

def rows(text, width):
    result = [line.rstrip().replace(' ', '.') for line in text.strip('\n').splitlines()]
    assert all(len(line) <= width for line in result), [len(r) for r in result]
    return [line.ljust(width, '.') for line in result]

